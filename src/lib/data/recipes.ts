/**
 * Built-in catalogue of easy, fitness-friendly recipes. Ingredients point to
 * the shopping catalogue (shop.ts), so nutrition and cost are computed, never
 * typed by hand. Grams are "as used": raw for rice/pasta/lentils, cooked for
 * couscous and noodles (see each shop item).
 */

export type RecipeCategory = "breakfast" | "main" | "bowl" | "snack";
export type CookMethod = "no_cook" | "pan" | "wok" | "pot" | "oven" | "microwave" | "blender";
